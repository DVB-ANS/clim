// Writes src/lib/worldDots.ts: the land dots of a world map on a diagonal grid (dotted-map) and
// the venues' approximate regions, so the landing page draws its map without shipping the library.
// Run: node scripts/make-world-dots.mjs
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const DottedMap = require("dotted-map").default ?? require("dotted-map");

const map = new DottedMap({ height: 56, grid: "diagonal" });
const pts = map.getPoints();
const w = Math.max(...pts.map((p) => p.x));
const h = Math.max(...pts.map((p) => p.y));
// The diagonal grid steps by 0.5 across and by sqrt(3) / 2 down: store x * 2 and the row index.
const ROW = Math.sqrt(3) / 2;
const flat = pts.flatMap((p) => [Math.round(p.x * 2), Math.round(p.y / ROW)]);

// Approximate regions, not exact data centres: Coinbase (US East), Kraken (US West), Binance and
// Hyperliquid (Tokyo), Deribit (London).
const regions = {
  Coinbase: [38.9, -77.4],
  Kraken: [37.77, -122.42],
  Binance: [35.68, 139.69],
  Hyperliquid: [35.6, 139.9],
  Deribit: [51.5, -0.12],
};
const pins = Object.fromEntries(
  Object.entries(regions).map(([name, [lat, lng]]) => {
    const p = map.getPin({ lat, lng });
    return [name, [Math.round(p.x * 10) / 10, Math.round(p.y * 10) / 10]];
  }),
);

const out = `// Generated by scripts/make-world-dots.mjs (dotted-map, height 56, diagonal grid). Do not edit.
export const WORLD_W = ${w};
export const WORLD_H = ${h};
/** Vertical step of the diagonal grid: y = row * WORLD_ROW. */
export const WORLD_ROW = Math.sqrt(3) / 2;
/** Land dots as x0 * 2, row0, x1 * 2, row1, ... */
export const WORLD_DOTS = "${flat.join(",")}";
/** Venues at their approximate regions (map units). */
export const VENUE_PINS: Record<string, [number, number]> = ${JSON.stringify(pins)};
`;
writeFileSync(new URL("../src/lib/worldDots.ts", import.meta.url), out);
console.log(`worldDots.ts: ${pts.length} dots, ${w} x ${h}`);
